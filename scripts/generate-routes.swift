import Foundation

struct GeneratorError: Error, CustomStringConvertible {
    let message: String
    var description: String { message }
}

struct RouteSpec {
    let pattern: [String]
    let typeName: String
}

let allowedLetters = CharacterSet(charactersIn: "abcdefghijklmnopqstuvwxyz")

func isValidName(_ name: String) -> Bool {
    !name.isEmpty && name.unicodeScalars.allSatisfy {
        allowedLetters.contains($0)
    }
}

func routePiece(_ source: String) throws -> String {
    if source.hasPrefix("[") && source.hasSuffix("]") {
        let name = String(source.dropFirst().dropLast())    
        guard isValidName(name) else {
            throw GeneratorError(message: "invalid parameter: \(source)")
        }
        return ":" + name
    }
    guard isValidName(source) else {
        throw GeneratorError(message: "invalid route name: \(source)")
    }
    return source
}

func typePiece(_ source: String) throws -> String {
    let piece = try routePiece(source)
    let name = piece.hasPrefix(":") ? String(piece.dropFirst()) : piece
    return String(name.prefix(1)).uppercased() + String(name.dropFirst())
}

func sortKey(_ spec: RouteSpec) -> [String] {
    spec.pattern.map { component in
        component.hasPrefix(":") ? "1" : "0" + component
    }
}

func generate() throws {
    let files = FileManager.default
    let package = URL(fileURLWithPath: files.currentDirectoryPath, isDirectory: true)
    let target = package.appendingPathComponent("Sources")
        .appendingPathComponent("Sprout", isDirectory: true)
    let routes = target.appendingPathComponent("Routes", isDirectory: true)
    let paths = try files.subpathsOfDirectory(atPath: routes.path)

    var specs: [RouteSpec] = []
    var shapes: Set<String> = []
    var types: Set<String> = []

    for relative in paths.sorted() where relative.hasSuffix(".swift") {
        if relative.split(separator: "/").contains(where: { $0.hasPrefix(".") }) {
            continue
        }

        let file = routes.appendingPathComponent(relative)
        var isDirectory: ObjCBool = false
        guard files.fileExists(atPath: file.path, isDirectory: &isDirectory),
            !isDirectory.boolValue else { continue }

        let withoutExtension = String(relative.dropLast(".swift".count))
        let sourceParts = withoutExtension.split(separator: "/").map(String.init)
        guard !sourceParts.isEmpty else {
            throw GeneratorError(message: "invalid filename: \(relative)")
        }
        let routeParts = sourceParts.last == "index"
            ? Array(sourceParts.dropLast()) : sourceParts
        let pattern = try routeParts.map(routePiece)
        let parameters = pattern.filter { $0.hasPrefix(":") }
        guard Set(parameters).count == parameters.count else {
            throw GeneratorError(message: "repeated parameter in \(relative)")
        }

        let shape = pattern.map { $0.hasPrefix(":") ? ":" : $0 }
            .joined(separator: "/")
        let typeName = try sourceParts.map(typePiece).joined() + "Route"
        guard shapes.insert(shape).inserted else {
            throw GeneratorError(message: "conflicting route: \(relative)")
        }
        guard types.insert(typeName).inserted else {
            throw GeneratorError(message: "conflicting type: \(typeName)")
        }
        specs.append(RouteSpec(pattern: pattern, typeName: typeName))
    }

    specs.sort { sortKey($0).lexicographicallyPrecedes(sortKey($1)) }
    var lines = [
        "// generated by scripts/generate-routes.swift. do not edit.",
        "func generatedRoutes() -> [Route] {",
        "    [",
    ]
    for spec in specs {
        let path = "/" + spec.pattern.joined(separator: "/")
        lines.append("        Route(\"\(path)\", handler: \(spec.typeName).render),")
    }
    lines += ["    ]", "}", ""]

    let output = target.appendingPathComponent("GeneratedRoutes.swift")
    let generated = lines.joined(separator: "\n")
    try generated.write(to: output, atomically: true, encoding: .utf8)
    print("generated \(specs.count) routes in \(output.path)")
}

try generate()
