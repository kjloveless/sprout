import Foundation

struct GeneratorError: Error, CustomStringConvertible {
    let message: String
    var description: String { message }
}

struct RouteSpec {
    let pattern: [String]
    let method: String
    let typeName: String
    let layouts: [String]
}

let letters = CharacterSet(charactersIn: "a"..."z")

func valid(_ value: String) -> Bool {
    !value.isEmpty && value.unicodeScalars.allSatisfy {
        letters.contains($0)
    }
}

func routePiece(_ source: String) throws -> String {
    if source.hasPrefix("[[") && source.hasSuffix("]]") {
        let name = String(source.dropFirst(2).dropLast(2))    
        guard valid(name) else {
            throw GeneratorError(message: "invalid: \(source)")
        }
        return ":" + name + "?"
    }
    if source.hasPrefix("[...") && source.hasSuffix("]") {
        let name = String(source.dropFirst(4).dropLast())
        guard valid(name) else {
            throw GeneratorError(message: "invalid \(source)")
        }
        return "*" + name
    }
    if source.hasPrefix("[") && source.hasSuffix("]") {
        let name = String(source.dropFirst().dropLast())
        guard valid(name) else {
            throw GeneratorError(message: "invalid \(source)")
        }
        return ":" + name
    }

    guard valid(source) else {
        throw GeneratorError(message: "invalid: \(source)")
    }
    return source
}

func typePiece(_ source: String) throws -> String {
    if source.hasPrefix("(") && source.hasSuffix(")") {
        let name = String(source.dropFirst().dropLast())
        guard valid(name) else {
            throw GeneratorError(message: "invalid route group: \(source)")
        }
        return "Group" + String(name.prefix(1)).uppercased() + String(name.dropFirst())
    }
    let piece = try routePiece(source)
    let marker = piece.hasPrefix("*") ? "Catchall" 
        : (piece.hasSuffix("?") ? "Optional" : "")
    let trimmed = piece.hasPrefix(":") || piece.hasPrefix("*")
        ? String(piece.dropFirst()) : piece
    let name = trimmed.hasSuffix("?") ? String(trimmed.dropLast()) : trimmed
    return marker + String(name.prefix(1)).uppercased() + String(name.dropFirst())
}

func sortKey(_ spec: RouteSpec) -> [String] {
    spec.pattern.map { component in
        if component.hasPrefix("*") { return "3" }
        if component.hasPrefix(":") { return component.hasSuffix("?") ? "2" : "1" }
        return "0" + component
    }
}

func generate() throws {
    let files = FileManager.default
    let package = URL(fileURLWithPath: files.currentDirectoryPath, isDirectory: true)
    let target = package.appendingPathComponent("Sources/Sprout", isDirectory: true)
    let routes = target.appendingPathComponent("Routes", isDirectory: true)
    let paths = try files.subpathsOfDirectory(atPath: routes.path).sorted()
    let header = "// generated by scripts/generate-routes.swift. do no edit.\n"

    var specs: [RouteSpec] = []
    var shapes: Set<String> = []
    var types: Set<String> = []
    var layouts: [String: String] = [:]
    var copies: [String: String] = [:]

    for relative in paths where relative == "_layout.swift"
        || relative.hasSuffix("/_layout.swift") {
        let parts = relative.split(separator: "/").map(String.init)
        if parts.contains(where: { $0.hasPrefix(".") }) { continue }
        let url = routes.appendingPathComponent(relative)
        var isDirectory: ObjCBool = false
        guard files.fileExists(atPath: url.path, isDirectory: &isDirectory),
            !isDirectory.boolValue else { continue }
        let parent = Array(parts.dropLast())
        let name = parent.isEmpty ? "Root" : try parent.map(typePiece).joined()
        let typeName = name + "Layout"
        guard !layouts.values.contains(typeName) else {
            throw GeneratorError(message:  "conflicting layout: \(typeName)")        
        }
        layouts[parent.joined(separator: "/")] = typeName
        copies["sprout-\(typeName).swift"] = header
            + (try String(contentsOf: url, encoding: .utf8))
    }

    for relative in paths where relative.hasSuffix(".swift") {
        if relative.split(separator: "/").contains(where: { $0.hasPrefix(".") }) {
            continue
        }
        if relative == "_layout.swift" || relative.hasSuffix("/_layout.swift") {
            continue
        }

        let url = routes.appendingPathComponent(relative)
        var isDirectory: ObjCBool = false
        guard files.fileExists(atPath: url.path, isDirectory: &isDirectory),
            !isDirectory.boolValue else { continue }

        let withoutExtension = String(relative.dropLast(".swift".count))
        var sourceParts = withoutExtension.split(separator: "/").map(String.init)
        guard let filename = sourceParts.popLast() else {
            throw GeneratorError(message: "invalid filename: \(relative)")
        }
        let suffixes = [".get", ".post", ".put", ".patch", ".delete", ".head"]
        let suffix = suffixes.first { filename.hasSuffix($0) }
        let method = suffix.map { String($0.dropFirst()).uppercased() } ?? "GET"
        let stem = suffix.map { String(filename.dropLast($0.count)) } ?? filename
        guard !(stem.hasPrefix("(") && stem.hasSuffix(")")) else {
            throw GeneratorError(message: "group must be a directory: \(relative)")
        }
        sourceParts.append(stem)
        let routeParts = sourceParts.last == "index"
            ? Array(sourceParts.dropLast()) : sourceParts
        var pattern: [String] = []
        for part in routeParts {
            if part.hasPrefix("(") && part.hasSuffix(")") {
                _ = try typePiece(part)
            } else {
                pattern.append(try routePiece(part))
            }
        }
        guard pattern.count <= 64,
            pattern.filter({ $0.hasPrefix(":") && $0.hasSuffix("?") }).count <= 8,
            !pattern.dropLast().contains(where: { $0.hasPrefix("*") }) else {
            throw GeneratorError(message: "unsupported route shape: \(relative)")        
        }
        let parameters = pattern.compactMap { component -> String? in
            guard component.hasPrefix(":") || component.hasPrefix("*") else { return nil }
            let name = String(component.dropFirst())
            return name.hasSuffix("?") ? String(name.dropLast()) : name
        }
        guard Set(parameters).count == parameters.count else {
            throw GeneratorError(message: "repeated parameter in \(relative)")
        }

        let shape = method + ":" + pattern.map { 
            if $0.hasPrefix("*") { return "*" } 
            if $0.hasPrefix(":") { return $0.hasSuffix("?") ? ":?" : ":" }
            return $0
        }.joined(separator: "/")
        let methodSuffix = suffix != nil
            ? method.prefix(1) + method.dropFirst().lowercased() : ""
        let typeName = try sourceParts.map(typePiece).joined() + methodSuffix + "Route"
        guard shapes.insert(shape).inserted else {
            throw GeneratorError(message: "conflicting route: \(relative)")
        }
        guard types.insert(typeName).inserted else {
            throw GeneratorError(message: "conflicting type: \(typeName)")
        }
        let directory = Array(sourceParts.dropLast())
        let inherited = (0...directory.count).compactMap { depth in
            layouts[directory.prefix(depth).joined(separator: "/")]
        }
        specs.append(RouteSpec(pattern: pattern, method: method,
                                typeName: typeName, layouts: inherited))
        copies["sprout-\(typeName).swift"] = header
            + (try String(contentsOf: url, encoding: .utf8))
    }

    specs.sort { 
        let left = sortKey($0), right = sortKey($1)
        return left == right ? $0.method < $1.method : left.lexicographicallyPrecedes(right) 
        }
    var lines = [
        "// generated by scripts/generate-routes.swift. do not edit.",
        "func generatedRoutes() -> [Route] {",
        "    [",
    ]
    for spec in specs {
        let path = "/" + spec.pattern.joined(separator: "/")
        lines.append("        Route(")
        lines.append("            \"\(path)\",")
        if spec.method != "GET" { lines.append("           method: .\(spec.method),") }
        if !spec.layouts.isEmpty {
            lines.append("            layouts: [")
            for layout in spec.layouts { lines.append("               \(layout).render,") }
            lines.append("           ],")
        }
        lines.append("           handler: \(spec.typeName).render")
        lines.append("        ),")
    }
    lines += ["    ]", "}", ""]

    let generatedDir = target.appendingPathComponent("Generated", isDirectory: true)
    try files.createDirectory(at: generatedDir, withIntermediateDirectories: true)
    let previous = try files.contentsOfDirectory(atPath: generatedDir.path)
        .filter { $0.hasPrefix("sprout-") && $0.hasSuffix(".swift") }
    for name in previous {
        let url = generatedDir.appendingPathComponent(name)
        guard (try String(contentsOf: url, encoding: .utf8)).hasPrefix(header) else {
            throw GeneratorError(message: "unrecognized generated file: \(name)")
        }
    }
    for name in previous where copies[name] == nil {
        try files.removeItem(at: generatedDir.appendingPathComponent(name))
    }
    for name in copies.keys.sorted() {
        try copies[name]!.write(to: generatedDir.appendingPathComponent(name),
                                atomically: true, encoding: .utf8)
    }
    let output = target.appendingPathComponent("GeneratedRoutes.swift")
    try lines.joined(separator: "\n").write(to: output, atomically: true, encoding: .utf8)
    print("generated \(specs.count) routes in \(output.path)")
}

try generate()
